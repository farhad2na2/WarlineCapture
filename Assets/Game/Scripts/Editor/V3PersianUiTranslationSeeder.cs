        private static readonly Regex LatinToken = new("[A-Za-z][A-Za-z0-9_.-]*", RegexOptions.Compiled);

        static V3PersianUiTranslationSeeder()
        {
            // Prefer the most specific term when phrases overlap (for example CIVILIAN TRUST
            // INCREASED before CIVILIAN TRUST). This keeps generated values grammatical and makes
            // the glossary safe to extend without depending on declaration order.
            Array.Sort(Phrases, (left, right) => right.Key.Length.CompareTo(left.Key.Length));
        }

        public static int FillMissing(
            IReadOnlyDictionary<string, string> english,
            IDictionary<string, string> persian)
        {
            _ = SeedTableRevision;
            int added = 0;
            foreach (KeyValuePair<string, string> entry in english)
            {
                if (persian.TryGetValue(entry.Key, out string current) &&
                    !string.IsNullOrWhiteSpace(current))
                {
                    continue;
                }

                if (!TryTranslate(entry.Value, out string translated))
                    continue;
                persian[entry.Key] = translated;
                added++;
            }
            return added;
        }

        private static bool TryTranslate(string source, out string translated)
        {
            translated = string.Empty;
            if (string.IsNullOrWhiteSpace(source))
                return false;

            string trimmed = source.Trim();
            if (Exact.TryGetValue(trimmed, out translated))
                return true;
            string canonical = Regex.Replace(trimmed, @"\s+", " ");
            if (!string.Equals(canonical, trimmed, StringComparison.Ordinal) &&
                Exact.TryGetValue(canonical, out translated))
            {
                return true;
            }

            trimmed = canonical;
            if (TryTranslatePattern(trimmed, out translated))
                return true;
            if (IdentityValues.Contains(trimmed) || LooksLikeDataValue(trimmed))
            {
                translated = trimmed;
                return true;
            }

            translated = trimmed;
            bool replaced = false;
            for (int i = 0; i < Phrases.Length; i++)
            {
                KeyValuePair<string, string> phrase = Phrases[i];
                string next = Regex.Replace(
                    translated,
                    $@"(?<![A-Za-z]){Regex.Escape(phrase.Key)}(?![A-Za-z])",
                    phrase.Value,
                    RegexOptions.IgnoreCase);
                if (!string.Equals(next, translated, StringComparison.Ordinal))
                {
                    translated = next;
                    replaced = true;
                }
            }

            foreach (KeyValuePair<string, string> word in Words)
            {
                string next = Regex.Replace(
                    translated,
                    $@"(?<![A-Za-z]){Regex.Escape(word.Key)}(?![A-Za-z])",
                    word.Value,
                    RegexOptions.IgnoreCase);
                if (!string.Equals(next, translated, StringComparison.Ordinal))
                {
                    translated = next;
                    replaced = true;
                }
            }

            if (!replaced)
                return false;

            MatchCollection leftovers = LatinToken.Matches(RemoveRichTextTags(translated));
            for (int i = 0; i < leftovers.Count; i++)
            {
                string token = leftovers[i].Value;
                if (!AllowedLatinTokens.Contains(token) && !IdentityValues.Contains(token))
                {
                    translated = string.Empty;
                    return false;
                }
            }

            translated = Regex.Replace(translated, @"[ \t]{2,}", " ").Trim();
            return translated.Length > 0;
        }

        private static bool TryTranslatePattern(string value, out string translated)
        {
            translated = string.Empty;

            Match duration = Regex.Match(
                value,
                @"^(?<days>\d+)D(?:\s+(?<hours>\d+)H)?(?:\s+(?<remaining>REMAINING))?$",
                RegexOptions.IgnoreCase);
            if (duration.Success)
            {
                List<string> parts = new();
                if (duration.Groups["days"].Success)
                    parts.Add($"{duration.Groups["days"].Value} روز");
                if (duration.Groups["hours"].Success)
                    parts.Add($"{duration.Groups["hours"].Value} ساعت");
                translated = string.Join(" و ", parts);
                if (duration.Groups["remaining"].Success)
                    translated += " باقی‌مانده";
                return true;
            }

            Match relative = Regex.Match(value, @"^(?<value>\d+)(?<unit>[hm])\s+ago$", RegexOptions.IgnoreCase);
            if (relative.Success)
            {
                string unit = relative.Groups["unit"].Value.Equals("h", StringComparison.OrdinalIgnoreCase)
                    ? "ساعت"
                    : "دقیقه";
                translated = $"{relative.Groups["value"].Value} {unit} پیش";
                return true;
            }

            // Measurements, file sizes, frame rates, and progress counters are locale-neutral data.
            if (Regex.IsMatch(value, @"^\d+(?:[.,]\d+)?\s*(?:KB|MB|FPS)$", RegexOptions.IgnoreCase) ||
                Regex.IsMatch(value, @"^[\d,]+\s*/\s*[\d,]+\s*XP$", RegexOptions.IgnoreCase) ||
                Regex.IsMatch(value, @"^\d+(?:\.\d+)?km\s+x\s+\d+(?:\.\d+)?km$", RegexOptions.IgnoreCase))
            {
                translated = value;
                return true;
            }

            return false;
        }

        private static bool LooksLikeDataValue(string value)
        {
            if (value.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase) ||
                value.EndsWith(".png", StringComparison.OrdinalIgnoreCase) ||
                value.StartsWith("upgrade.", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }

            bool hasLetter = false;
            bool hasDigit = false;
            bool hasDataSeparator = false;
            for (int i = 0; i < value.Length; i++)
            {
                hasLetter |= char.IsLetter(value[i]);
                hasDigit |= char.IsDigit(value[i]);
                hasDataSeparator |= value[i] is '_' or '/' or '\\' or '=';
            }
            return !hasLetter || !value.Contains(' ') && (hasDigit || hasDataSeparator);
        }

        private static string RemoveRichTextTags(string value) =>
            Regex.Replace(value ?? string.Empty, "<[^>]+>", string.Empty);

        private static KeyValuePair<string, string> Pair(string source, string value) => new(source, value);
